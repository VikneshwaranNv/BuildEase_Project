/**
 * Robust interpolation-aware translation accessor with fallback chain:
 * lang -> en -> key
 */
export function getTranslation(
  lang: LanguageCode,
  key: string,
  params?: Record<string, string | number>
): string {
  const langDict = translations[lang] || translations.en;
  let text = langDict[key] ?? translations.en[key] ?? key;

  if (params && typeof text === 'string') {
    for (const [paramKey, paramValue] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${paramKey}\\}`, 'g'), String(paramValue));
    }
  }

  return text;
}

/**
 * Returns key counts per language and any missing keys relative to English master dictionary
 */
export function getTranslationAudit() {
  const masterKeys = Object.keys(translations.en);
  const audit: Record<LanguageCode, { totalKeys: number; missingKeys: string[] }> = {
    en: { totalKeys: masterKeys.length, missingKeys: [] },
    hi: { totalKeys: 0, missingKeys: [] },
    mr: { totalKeys: 0, missingKeys: [] },
    as: { totalKeys: 0, missingKeys: [] },
    bn: { totalKeys: 0, missingKeys: [] },
  };

  (['hi', 'mr', 'as', 'bn'] as LanguageCode[]).forEach((code) => {
    const dict = translations[code] || {};
    const missing = masterKeys.filter((k) => dict[k] === undefined || dict[k] === '');
    audit[code] = {
      totalKeys: Object.keys(dict).length,
      missingKeys: missing,
    };
  });

  return audit;
}
